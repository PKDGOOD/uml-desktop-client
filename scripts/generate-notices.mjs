import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(await fs.readFile(path.join(root, 'package-lock.json'), 'utf8'));
// Include all production packages (even build-time helpers) and the actual desktop runtime.
const entries = Object.entries(lock.packages).filter(([location, pkg]) => location && (!pkg.dev || location === 'node_modules/electron'));
const sections = [];
for (const [location, locked] of entries.sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  const directory = path.join(root, location);
  const pkg = JSON.parse(await fs.readFile(path.join(directory, 'package.json'), 'utf8'));
  if (pkg.version !== locked.version) throw new Error(`Run npm ci: installed version differs for ${pkg.name}`);
  const files = (await fs.readdir(directory, { withFileTypes: true }))
    .filter((file) => file.isFile() && /^(licen[cs]e|copying|notice|thirdpartynotices)([._-]|$)/i.test(file.name))
    .map((file) => file.name).sort();
  if (!files.length) throw new Error(`No license text found for ${pkg.name}; review before distribution`);
  const texts = [];
  for (const file of files) texts.push(`### ${file}\n\n\`\`\`text\n${(await fs.readFile(path.join(directory, file), 'utf8')).replace(/\r\n/g, '\n').trim()}\n\`\`\`\n`);
  sections.push(`## ${pkg.name}@${pkg.version}\n\nDeclared license: ${pkg.license ?? locked.license ?? 'REVIEW REQUIRED'}\n\n${texts.join('\n')}`);
}
const output = `# Third-party notices\n\nGenerated by \`npm run notices\` from installed packages matching package-lock.json. Do not edit by hand.\n\nThis conservative inventory includes all production dependency entries and Electron, even when a helper is not bundled. Dependencies retain their own copyright and license terms. It is not a full legal or asset-provenance review. Desktop releases must additionally include Electron's \`LICENSES.chromium.html\`; packaging copies the version installed with Electron.\n\n${sections.join('\n')}`;
const target = path.join(root, 'THIRD_PARTY_NOTICES.md');
if (process.argv.includes('--check')) {
  if (await fs.readFile(target, 'utf8').catch(() => '') !== output) throw new Error('Third-party notices are stale. Run npm run notices.');
  console.log(`Third-party notices match ${entries.length} locked package entries.`);
} else {
  await fs.writeFile(target, output);
  console.log(`Wrote notices for ${entries.length} locked package entries.`);
}
